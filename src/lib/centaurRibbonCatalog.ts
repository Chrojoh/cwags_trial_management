export function ribbonUnitPrice(code: string, currency: RibbonCurrency, quantity: number) {
  const product = CENTAUR_2026_PRODUCTS.find((item) => item.code === code);
  if (!product) return 0;
  const prices = currency === 'CAD' ? product.cad : product.usd;
  const tiers = product.tiers || [1];
  let index = 0;
  tiers.forEach((minimum, candidate) => {
    if (quantity >= minimum) index = candidate;
  });
  return prices[Math.min(index, prices.length - 1)] || 0;
}

export function ribbonProduct(code: string) {
  return CENTAUR_2026_PRODUCTS.find((item) => item.code === code);
}
